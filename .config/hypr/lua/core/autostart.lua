local config = require("lua.config")

hl.config({ autogenerated = false })

hl.on("hyprland.start", function()
    hl.exec_cmd(
        "dbus-update-activation-environment --systemd " ..
        "WAYLAND_DISPLAY XDG_CURRENT_DESKTOP " ..
        "XDG_SESSION_DESKTOP XDG_SESSION_TYPE"
    )

    hl.exec_cmd(
        "systemctl --user import-environment " ..
        "WAYLAND_DISPLAY XDG_CURRENT_DESKTOP " ..
        "XDG_SESSION_DESKTOP XDG_SESSION_TYPE"
    )

    hl.exec_cmd("nm-applet --indicator")
    hl.exec_cmd("mako")

    hl.exec_cmd(
        "/usr/lib/polkit-gnome/" ..
        "polkit-gnome-authentication-agent-1"
    )

    hl.exec_cmd(
        "/usr/bin/gnome-keyring-daemon " ..
        "--start --components=pkcs11,secrets,ssh,gpg"
    )

    hl.exec_cmd("foot --server")

    hl.exec_cmd(
        "bash " ..
        config.paths.config ..
        "/swww/start.sh slideshow"
    )

    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("wl-paste --type image --watch cliphist store")

    hl.exec_cmd("xrdb -load " .. config.paths.home .. "/.Xresources")
    hl.exec_cmd("apply-gsettings")

    hl.exec_cmd("quickshell")
end)
